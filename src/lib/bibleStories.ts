/**
 * Get a story by its ID.
 */
export function getStoryById(id: string): BibleStory | undefined {
  return BIBLE_STORIES.find((s) => s.id === id);
}

/**
 * Get all stories in a category, for the Bookshelf view.
 */
export function getStoriesByCategory(category: StoryCategory): BibleStory[] {
  return BIBLE_STORIES.filter((s) => s.category === category);
}

/**
 * Get a random story (the "Another Story" button).
 * Optionally exclude a story ID to avoid repeats.
 */
export function getRandomStory(excludeId?: string): BibleStory {
  const pool = excludeId
    ? BIBLE_STORIES.filter((s) => s.id !== excludeId)
    : BIBLE_STORIES;
  return pool[Math.floor(Math.random() * pool.length)];
}

