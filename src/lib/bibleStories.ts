/**
 * Bible story catalog — the core content dataset for the app.
 *
 * Each story has metadata used for:
 * - Display: title, category, themes, testament
 * - AI generation: scriptureRef tells Claude which passage to retell
 * - Bookshelf: category groups stories into shelves
 * - Progress: id tracks which stories have been heard
 */

